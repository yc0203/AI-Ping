// Reuse the already-downloaded official Electron runtime, with a separate application archive and data folder.
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const source = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(source, '..');
const require = createRequire(import.meta.url);
const asar = require('@electron/asar');
const runtime = join(root, 'app');
const target = join(source, 'dist', 'win-unpacked');
const stage = join(source, 'build', 'local-package');
await mkdir(target, { recursive: true });
await cp(runtime, target, { recursive: true, filter: path => !path.endsWith('Uninstall lolPing.exe') && !path.endsWith('lolPing.exe') && !path.includes(`${join(runtime, 'data')}`) });
await cp(join(runtime, 'lolPing.exe'), join(target, 'AI-Ping.exe'));
await mkdir(stage, { recursive: true });
await cp(join(source, 'out'), join(stage, 'out'), { recursive: true });
await cp(join(source, 'LICENSE'), join(stage, 'LICENSE'));
await writeFile(join(stage, 'package.json'), JSON.stringify({ name: 'ai-ping', productName: 'AI-Ping', version: '0.1.0', main: 'out/main/index.js', license: 'MIT' }));
await asar.createPackage(stage, join(target, 'resources', 'app.asar'));
const script = (await readFile(join(source, 'native', 'text-selection.ps1'), 'utf8')).replace(/^\uFEFF/, '');
await writeFile(join(target, 'resources', 'text-selection.ps1'), '\uFEFF'+script);
await mkdir(join(target, 'tools'), { recursive: true });
await cp(join(source, 'tools', 'configure-ai.ps1'), join(target, 'tools', 'configure-ai.ps1'));
await cp(join(source, 'README.md'), join(target, 'README.md'));
await cp(join(source, 'LICENSE'), join(target, 'LICENSE'));
await mkdir(join(target, 'docs'), { recursive: true });
await cp(join(source, 'docs', 'INSTALL.md'), join(target, 'docs', 'INSTALL.md'));
console.log('Packaged independent preview:', join(target, 'AI-Ping.exe'));
